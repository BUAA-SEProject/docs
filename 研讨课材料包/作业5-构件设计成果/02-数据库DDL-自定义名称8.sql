-- SHARE 学术成果分享平台 · PostgreSQL 物理模型 · 01组 自定义名称8
-- 在空的 SHARE 数据库执行。应用连接使用最小权限角色。
BEGIN;

CREATE TABLE institutions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(240) NOT NULL CHECK (btrim(name) <> ''),
    normalized_name varchar(240) NOT NULL,
    ror_id varchar(32) UNIQUE,
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (normalized_name)
);

CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL CHECK (email = lower(btrim(email))),
    password_hash text NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (status IN ('UNVERIFIED', 'ACTIVE', 'DISABLED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (email)
);

CREATE TABLE account_roles (
    account_id bigint NOT NULL REFERENCES accounts(id),
    role_code varchar(24) NOT NULL
        CHECK (role_code IN ('USER', 'CLAIM_REVIEWER', 'COLLECTION_ADMIN', 'ADMIN')),
    PRIMARY KEY (account_id, role_code)
);

CREATE TABLE scholars (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name varchar(160) NOT NULL CHECK (btrim(display_name) <> ''),
    normalized_name varchar(160) NOT NULL,
    orcid varchar(19) UNIQUE,
    institution_id bigint REFERENCES institutions(id),
    public_bio text,
    public_profile boolean NOT NULL DEFAULT false,
    source_version bigint NOT NULL DEFAULT 1 CHECK (source_version > 0),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_scholars_institution_name ON scholars (institution_id, normalized_name);
CREATE INDEX ix_scholars_name ON scholars (normalized_name);

CREATE TABLE works (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type varchar(16) NOT NULL CHECK (type IN ('PAPER','PATENT','PROJECT','AWARD')),
    title varchar(1000) NOT NULL CHECK (btrim(title) <> ''),
    abstract text,
    year smallint CHECK (year BETWEEN 1500 AND 9999),
    event_date date,
    doi varchar(255) CHECK (doi = lower(btrim(doi))),
    canonical_key varchar(320),
    venue varchar(300),
    keywords text[] NOT NULL DEFAULT '{}',
    type_details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(type_details) = 'object'),
    citation_count integer CHECK (citation_count >= 0),
    visibility varchar(16) NOT NULL DEFAULT 'DRAFT'
        CHECK (visibility IN ('DRAFT', 'PUBLISHED', 'WITHDRAWN')),
    source_version bigint NOT NULL DEFAULT 1 CHECK (source_version > 0),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (event_date IS NULL OR (year IS NOT NULL AND extract(year FROM event_date) = year))
);
CREATE UNIQUE INDEX ux_works_doi ON works (doi) WHERE doi IS NOT NULL;
CREATE UNIQUE INDEX ux_works_canonical ON works (canonical_key) WHERE canonical_key IS NOT NULL;
CREATE INDEX ix_works_public_type_year ON works (type, year DESC NULLS LAST, event_date DESC NULLS LAST, id)
    WHERE visibility = 'PUBLISHED';

CREATE TABLE research_fields (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES research_fields(id),
    code varchar(48) NOT NULL UNIQUE,
    name varchar(160) NOT NULL,
    sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    active boolean NOT NULL DEFAULT true,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (parent_id IS DISTINCT FROM id)
);
CREATE INDEX ix_research_fields_children ON research_fields (parent_id, sort_order, id);

CREATE TABLE work_research_fields (
    work_id bigint NOT NULL REFERENCES works(id),
    field_id bigint NOT NULL REFERENCES research_fields(id),
    PRIMARY KEY (work_id, field_id)
);
CREATE INDEX ix_work_fields_by_field ON work_research_fields (field_id, work_id);

CREATE TABLE work_scholars (
    work_id bigint NOT NULL REFERENCES works(id),
    scholar_id bigint NOT NULL REFERENCES scholars(id),
    author_order integer NOT NULL CHECK (author_order > 0),
    role_code varchar(16) NOT NULL DEFAULT 'AUTHOR'
        CHECK (role_code IN ('AUTHOR', 'INVENTOR', 'CONTRIBUTOR')),
    affiliation_id bigint REFERENCES institutions(id),
    PRIMARY KEY (work_id, scholar_id),
    UNIQUE (work_id, author_order)
);
CREATE INDEX ix_work_scholars_reverse ON work_scholars (scholar_id, work_id);
CREATE INDEX ix_work_scholars_affiliation ON work_scholars (affiliation_id, work_id)
    WHERE affiliation_id IS NOT NULL;

CREATE TABLE claim_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scholar_id bigint NOT NULL REFERENCES scholars(id),
    applicant_account_id bigint NOT NULL REFERENCES accounts(id),
    status varchar(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reason varchar(1000) NOT NULL CHECK (btrim(reason) <> ''),
    reviewer_account_id bigint REFERENCES accounts(id),
    review_comment varchar(1000),
    reviewed_at timestamptz,
    request_key varchar(128) NOT NULL,
    request_hash char(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (applicant_account_id, request_key),
    UNIQUE (id, applicant_account_id),
    UNIQUE (id, scholar_id, applicant_account_id, status),
    CHECK (reviewer_account_id IS DISTINCT FROM applicant_account_id),
    CHECK (
        (status = 'PENDING' AND reviewer_account_id IS NULL AND reviewed_at IS NULL AND review_comment IS NULL)
        OR
        (status = 'APPROVED' AND reviewer_account_id IS NOT NULL AND reviewed_at IS NOT NULL)
        OR
        (status = 'REJECTED' AND reviewer_account_id IS NOT NULL AND reviewed_at IS NOT NULL
         AND review_comment IS NOT NULL AND btrim(review_comment) <> '')
    )
);
CREATE UNIQUE INDEX ux_claims_same_pending ON claim_applications (scholar_id, applicant_account_id)
    WHERE status = 'PENDING';
CREATE INDEX ix_claims_queue ON claim_applications (status, created_at DESC, id DESC);
CREATE INDEX ix_claims_applicant ON claim_applications (applicant_account_id, created_at DESC);

CREATE TABLE claim_proofs (
    evidence_id uuid PRIMARY KEY,
    uploader_account_id bigint NOT NULL REFERENCES accounts(id),
    claim_id bigint,
    object_key text NOT NULL UNIQUE,
    media_type varchar(48) NOT NULL CHECK (media_type IN ('application/pdf', 'image/jpeg', 'image/png')),
    byte_size integer NOT NULL CHECK (byte_size BETWEEN 1 AND 10485760),
    status varchar(16) NOT NULL DEFAULT 'UPLOADED'
        CHECK (status IN ('UPLOADED', 'VERIFIED', 'REJECTED')),
    expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (claim_id, uploader_account_id) REFERENCES claim_applications(id, applicant_account_id),
    CHECK (claim_id IS NULL OR (status = 'VERIFIED' AND expires_at IS NULL))
);
CREATE INDEX ix_claim_proofs_claim ON claim_proofs (claim_id) WHERE claim_id IS NOT NULL;

CREATE TABLE scholar_claim_bindings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scholar_id bigint NOT NULL REFERENCES scholars(id),
    account_id bigint NOT NULL REFERENCES accounts(id),
    approved_claim_id bigint NOT NULL UNIQUE,
    approved_status varchar(16) GENERATED ALWAYS AS ('APPROVED'::varchar(16)) STORED,
    bound_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz,
    revoked_by bigint REFERENCES accounts(id),
    CHECK ((revoked_at IS NULL) = (revoked_by IS NULL)),
    CHECK (revoked_at IS NULL OR revoked_at >= bound_at),
    FOREIGN KEY (approved_claim_id, scholar_id, account_id, approved_status)
        REFERENCES claim_applications(id, scholar_id, applicant_account_id, status)
);
CREATE UNIQUE INDEX ux_scholar_live_binding ON scholar_claim_bindings (scholar_id)
    WHERE revoked_at IS NULL;
CREATE INDEX ix_bindings_account ON scholar_claim_bindings (account_id) WHERE revoked_at IS NULL;

CREATE TABLE collection_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code varchar(64) NOT NULL UNIQUE,
    source_name varchar(160) NOT NULL,
    enabled boolean NOT NULL DEFAULT false,
    policy_revision varchar(128) NOT NULL,
    min_interval_ms integer NOT NULL CHECK (min_interval_ms > 0),
    checkpoint jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(checkpoint) = 'object'),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE collection_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES collection_sources(id),
    created_by bigint NOT NULL REFERENCES accounts(id),
    mode varchar(16) NOT NULL CHECK (mode IN ('FULL','INCREMENTAL')),
    status varchar(16) NOT NULL DEFAULT 'QUEUED'
        CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED')),
    request_key varchar(128) NOT NULL,
    request_hash char(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    checkpoint jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(checkpoint) = 'object'),
    processed_count bigint NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    imported_count bigint NOT NULL DEFAULT 0 CHECK (imported_count >= 0),
    error_count bigint NOT NULL DEFAULT 0 CHECK (error_count >= 0),
    attempt smallint NOT NULL DEFAULT 0 CHECK (attempt >= 0),
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    lease_token uuid,
    lease_until timestamptz,
    failure_code varchar(64),
    failure_message varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    started_at timestamptz,
    finished_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (created_by, request_key),
    UNIQUE (id, source_id),
    CHECK (imported_count + error_count <= processed_count),
    CHECK ((status = 'RUNNING') = (lease_token IS NOT NULL AND lease_until IS NOT NULL)),
    CHECK ((lease_token IS NULL) = (lease_until IS NULL)),
    CHECK ((status IN ('SUCCEEDED', 'FAILED')) = (finished_at IS NOT NULL)),
    CHECK ((status = 'FAILED') = (failure_code IS NOT NULL)),
    CHECK (failure_message IS NULL OR status = 'FAILED'),
    CHECK (started_at IS NULL OR started_at >= created_at),
    CHECK (finished_at IS NULL OR (started_at IS NOT NULL AND finished_at >= started_at))
);
CREATE UNIQUE INDEX ux_collection_tasks_source_live ON collection_tasks (source_id)
    WHERE status IN ('QUEUED','RUNNING');
CREATE INDEX ix_collection_tasks_take ON collection_tasks (next_attempt_at, id) WHERE status = 'QUEUED';
CREATE INDEX ix_collection_tasks_expired ON collection_tasks (lease_until, id) WHERE status = 'RUNNING';
CREATE INDEX ix_collection_tasks_admin ON collection_tasks (status, created_at DESC, id DESC);

CREATE TABLE work_sources (
    source_id bigint NOT NULL REFERENCES collection_sources(id),
    native_key varchar(320) NOT NULL,
    work_id bigint NOT NULL REFERENCES works(id),
    source_url text,
    provider_updated_at timestamptz,
    payload_hash char(64) NOT NULL CHECK (payload_hash ~ '^[0-9a-f]{64}$'),
    raw_object_key text NOT NULL,
    last_task_id bigint,
    seen_at timestamptz NOT NULL DEFAULT now(),
    invalidated_at timestamptz,
    PRIMARY KEY (source_id, native_key),
    FOREIGN KEY (last_task_id, source_id) REFERENCES collection_tasks(id, source_id)
);
CREATE INDEX ix_work_sources_active ON work_sources (work_id) WHERE invalidated_at IS NULL;

CREATE TABLE audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_account_id bigint REFERENCES accounts(id),
    actor_kind varchar(16) NOT NULL CHECK (actor_kind IN ('ACCOUNT','SYSTEM')),
    action varchar(64) NOT NULL,
    target_kind varchar(32) NOT NULL,
    target_id bigint NOT NULL CHECK (target_id > 0),
    result varchar(16) NOT NULL CHECK (result IN ('SUCCEEDED','FAILED')),
    request_id varchar(64) NOT NULL,
    details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((actor_kind = 'ACCOUNT') = (actor_account_id IS NOT NULL))
);
CREATE INDEX ix_audit_target_time ON audit_logs (target_kind, target_id, created_at DESC, id DESC);
CREATE INDEX ix_audit_request ON audit_logs (request_id);

CREATE TABLE outbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_kind varchar(32) NOT NULL,
    object_id bigint NOT NULL CHECK (object_id > 0),
    object_version bigint NOT NULL CHECK (object_version > 0),
    event_type varchar(64) NOT NULL,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    available_at timestamptz NOT NULL DEFAULT now(),
    processed_at timestamptz,
    last_error_code varchar(64),
    UNIQUE (object_kind, object_id, object_version, event_type)
);
CREATE INDEX ix_outbox_available ON outbox_events (available_at, id) WHERE processed_at IS NULL;
CREATE INDEX ix_outbox_public_safety ON outbox_events (id)
    WHERE processed_at IS NULL AND event_type IN ('WORK_WITHDRAWN', 'WORK_PUBLIC_REDACTED');

CREATE TABLE stat_works_year_type (
    year smallint NOT NULL CHECK (year = 0 OR year BETWEEN 1500 AND 9999),
    type varchar(16) NOT NULL CHECK (type IN ('PAPER','PATENT','PROJECT','AWARD')),
    work_count bigint NOT NULL CHECK (work_count >= 0),
    as_of timestamptz NOT NULL,
    PRIMARY KEY (year, type)
);
-- year=0 是副本内的未知年份桶，年度统计接口排除此桶。成果详情的未知年份仍表示为空值。

COMMIT;
